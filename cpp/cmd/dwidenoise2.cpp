template <typename T>
void run(Header &dwi,
         const Demodulation &demodulation,
         const demean_type demean,
         Image<float> &user_vst_image,
         const std::vector<Iterative::Iteration> &iterations,
         const decomp_type decomposition,
         std::shared_ptr<Estimator::Base> estimator,
         filter_type filter,
         aggregator_type aggregator,
         const bias_handling_t bias_handling,
         const debias_anchor_t debias_anchor,
         const std::string &output_name,
         Exports &final_exports) {

  Image<T> input(dwi.get_image<T>());
  Image<bool> mask = generate_mask(input);
  Image<float> vst_image(user_vst_image);

  // Noise model governing the variance-stabilising transform, configured from
  //   the -noise_dof and -vst_method options (Gaussian for complex data).
  std::shared_ptr<NoiseModel::Base> noise_model = make_noise_model(is_complex<T>::value);

  Precondition<T> preconditioner(input, demodulation, demean, user_vst_image, noise_model);
  Image<T> input_preconditioned;

  // Per-voxel signal-rank density used to size the rank-adaptive reconstruction kernel. Normally
  //   accumulated across the noise-estimation iterations below; for a single-row schedule there are
  //   no such iterations, so an externally-supplied map (-rankpermm_in, e.g. exported by dwi2noise)
  //   may seed it. run() rejects -rankpermm_in with a multi-row schedule, so when the iteration loop
  //   runs it overwrites this seed (as intended) rather than mixing the two.
  Image<float> rank_per_mm;
  {
    auto opt_rpm_in = get_options("rankpermm_in");
    if (!opt_rpm_in.empty())
      rank_per_mm = Denoise::import_rank_per_mm_map(opt_rpm_in[0][0], dwi);
  }

  // Random number generator for drawing temporal sub-sampling subsets.
  Math::RNG rng;
  constexpr ssize_t temporal_min_per_group = 2;

  // All but the last iteration: estimate (and progressively refine) the noise level.
  for (ssize_t iteration = 0; iteration != iterations.size() - 1; ++iteration) {
    // Draw this iteration's temporal subset (stratified by demeaning group) and (re)compute
    //   the stabilised-domain per-group means over that same subset, under the current noise
    //   level map. The preconditioned data then hold only the m' subset volumes, so the
    //   downstream Estimate / kernel sizing see m' volumes without any knowledge of sub-sampling.
    preconditioner.set_temporal_subsample(iterations[iteration].temporal_subsample, rng, temporal_min_per_group);
    // Resolve the partition count for this iteration from the (post-subsampling) volume count m'.
    //   When partitioning, the preconditioner performs no demeaning (done per partition within
    //   Estimate); set this before update_vst_parameters so it skips the now-unused mean pass.
    const ssize_t mprime = preconditioner.header().size(3);
    const ssize_t num_partitions = Iterative::resolve_num_partitions(iterations[iteration], mprime);
    if (num_partitions > 1 && !estimator->supports_partitioning())
      throw Exception("The selected noise level estimator does not support volume partitioning "
                      "(schedule iteration " + str(iteration + 1) + " requests " + str(num_partitions) +
                      " partitions); choose a different -estimator or remove partitioning from the schedule");
    preconditioner.set_partitioning_active(num_partitions > 1);
    preconditioner.update_vst_parameters(vst_image, input);
    estimator->update_vst_image(vst_image);
    input_preconditioned =
        Image<T>::scratch(preconditioner.header(), "Preconditioned version of \"" + dwi.name() + "\"");

    // Per-kernel partitioning: each PCA patch draws its own balanced assignment (in Estimate,
    //   from a voxel-seeded RNG), so only the per-volume demeaning-group labels and the partition
    //   count are passed; no single shared (per-level) assignment is built.
    std::vector<ssize_t> volume_group;
    std::shared_ptr<const Partitioning> partitioning; // null ⇒ per-kernel in Estimate
    if (num_partitions > 1)
      volume_group = preconditioner.output_volume_to_group();

    std::shared_ptr<SpatialSubsample> subsample =
        std::make_shared<SpatialSubsample>(dwi, iterations[iteration].spatial_subsample_ratios);
    // For internal iterations, we only save the output noise level estimate
    Exports iteration_exports(dwi, subsample->header());
    iteration_exports.set_noise_out();
    iteration_exports.set_rank_input();
    iteration_exports.set_max_dist();
    Iterative::estimate(input,
                        input_preconditioned,
                        mask,
                        vst_image,
                        rank_per_mm,
                        iterations[iteration],
                        iteration,
                        subsample,
                        decomposition,
                        estimator,
                        preconditioner,
                        iteration_exports,
                        num_partitions,
                        partitioning,
                        volume_group);
    // Propagate result to next iteration
    vst_image = Denoise::condition_noise_map(iteration_exports.noise_out,
                                             noise_impute_type::NAN_TO_ZERO,
                                             noise_pad_type::PAD,
                                             iterations[iteration].smooth_noiseout);
    // Signal-rank density (per mm of kernel radius) used to size the next iteration's rank-based
    //   kernel. Under partitioning the rank-based kernel is sized from the smallest partition
    //   (m'/P), so the density must be *per partition*: rank_input is the signal rank summed over
    //   the iteration's num_partitions partitions, so divide by that count. num_partitions is the
    //   count for the iteration that produced rank_input (it may differ between iterations).
    rank_per_mm = Denoise::compute_rank_per_mm(iteration_exports.rank_input, iteration_exports.max_dist, num_partitions);
  }

  // Final (reconstruction) pass: the schedule's final row is validated to have
  //   temporal_subsample == 1, so all volumes are reconstructed. Clear any subset and
  //   recompute the full-data means under the final noise level map.
  preconditioner.set_temporal_subsample(1.0, rng, temporal_min_per_group);
  // Resolve partitioning for the reconstruction pass (sized from the full volume count, as the
  //   final row's temporal_subsample is validated to be 1.0). Set before update_vst_parameters
  //   so the (unused) preconditioner-side demeaning pass is skipped when partitioning.
  const ssize_t mprime_final = preconditioner.header().size(3);
  const ssize_t num_partitions = Iterative::resolve_num_partitions(iterations.back(), mprime_final);
  preconditioner.set_partitioning_active(num_partitions > 1);
  preconditioner.update_vst_parameters(vst_image, input);
  estimator->update_vst_image(vst_image);

  auto subsample = std::make_shared<SpatialSubsample>(dwi, iterations.back().spatial_subsample_ratios);

  // Implementation from here differs to that of dwi2noise
  auto opt = get_options("preconditioned_input");
  if (!opt.empty())
    input_preconditioned = Image<T>::create(opt[0][0], preconditioner.header());
  else
    input_preconditioned =
        Image<T>::scratch(preconditioner.header(), "Preconditioned version of \"" + dwi.name() + "\"");

  // Optionally export the signal-rank density that sizes the reconstruction kernel (the same quantity
  //   dwi2noise -rankpermm_out exports). Available only when a noise-estimation iteration derived it
  //   or it was supplied via -rankpermm_in; a bare single-row schedule has none.
  opt = get_options("rankpermm_out");
  if (!opt.empty()) {
    if (rank_per_mm.valid()) {
      Header H_rpm(rank_per_mm);
      Image<float> rpm_out = Image<float>::create(opt[0][0].as_text(), H_rpm);
      for (auto l = Loop(rpm_out)(rank_per_mm, rpm_out); l; ++l)
        rpm_out.value() = rank_per_mm.value();
    } else {
      WARN("-rankpermm_out: no signal-rank density is available to export "
           "(the schedule performed no noise-estimation iteration and none was supplied via "
           "-rankpermm_in); nothing written");
    }
  }

  auto kernel = Kernel::make_kernel(input_preconditioned,
                                    subsample->get_factors(),
                                    iterations.back().kernel_size_multiplier,
                                    rank_per_mm,
                                    Denoise::num_volumes(input),
                                    num_partitions);
  kernel->set_mask(mask);

  // Unless the final schedule row is configured to (re)estimate the noise level, assume the
  //   variance-stabilising transform yields a noise level of 1.0 everywhere (dummy Unity
  //   estimator), carrying through the estimate refined by the preceding iterations.
  if (!iterations.back().update_noise.value())
    estimator.reset(new Estimator::Unity());

  if (num_partitions > 1 && !estimator->supports_partitioning())
    throw Exception("The selected noise level estimator does not support volume partitioning "
                    "(final schedule row requests " + str(num_partitions) +
                    " partitions); choose a different -estimator or remove partitioning from the schedule");
  if (num_partitions > 1 && debias_anchor == debias_anchor_t::GROUP_MEAN)
    throw Exception("The GROUP_MEAN debias anchor is incompatible with volume partitioning; "
                    "use -debias_anchor sample (the default) when partitioning is enabled");

  // Per-kernel partitioning (see the estimation loop above): pass only the demeaning-group
  //   labels and the partition count; Recon's Estimate base draws a per-patch assignment.
  std::vector<ssize_t> volume_group;
  std::shared_ptr<const Partitioning> partitioning; // null ⇒ per-kernel in Estimate/Recon
  if (num_partitions > 1)
    volume_group = preconditioner.output_volume_to_group();

  preconditioner(input, input_preconditioned, false);
  Recon<T> func(input_preconditioned,
                subsample,
                kernel,
                decomposition,
                estimator,
                filter,
                aggregator,
                final_exports,
                preconditioner.null_rank(),
                partitioning,
                volume_group,
                num_partitions);

  Header H_out (dwi);
  H_out.datatype() = DataType::from<T>();
  Image<T> output = Image<T>::create(output_name, H_out);
  Image<T> output_preconditioned;
  opt = get_options("preconditioned_output");
  if (!opt.empty())
    output_preconditioned = Image<T>::create(opt[0][0], preconditioner.header());
  // If we can make use of the output image for preconditioned denoised data
  //   rather than explicitly allocating an intermediate scratch buffer for that purpose,
  //   then do so
  else if (DataType::from<T>() == dwi.datatype() && dwi.ndim() == 4)
    output_preconditioned = output;
  else
    output_preconditioned = Image<T>::scratch(                              //
        preconditioner.header(),                                            //
        "Scratch buffer for denoised data before undoing preconditioning"); //

  const bool final_iteration_includes_MP =
      iterations.back().update_noise.value() && get_options("fixed_rank").empty();
  ThreadedLoop(final_iteration_includes_MP                                 //
                   ? "running MP-PCA noise level estimation and denoising" //
                   : "running PCA denoising",                              //
               input_preconditioned,                                       //
               0,                                                          //
               3)                                                          //
      .run(func, input_preconditioned, output_preconditioned);             //
  func.report_warnings();
  // Note: Denoise::condition_noise_map() is intentionally _not_ called here:
  //   noise estimates are fed through as-is

  const size_t max_rank = Denoise::num_volumes(dwi);

  // Rescale output if aggregation was performed
  if (aggregator != aggregator_type::EXCLUSIVE) {
    for (auto l_voxel = Loop(final_exports.sum_aggregation)      //
         (output_preconditioned, final_exports.sum_aggregation); //
         l_voxel;                                                //
         ++l_voxel) {                                            //
      const float sum_aggregation = final_exports.sum_aggregation.value();
      if (sum_aggregation != 0.0F) {
        const double multiplier = 1.0 / static_cast<double>(sum_aggregation);
        for (auto l_volume = Loop(3)(output_preconditioned); l_volume; ++l_volume)
          output_preconditioned.value() *= multiplier;
      }
    }
    if (final_exports.rank_output.valid()) {
      for (auto l = Loop(final_exports.sum_aggregation)                //
           (final_exports.rank_output, final_exports.sum_aggregation); //
           l;                                                          //
           ++l) {                                                      //
        const float sum_aggregation = final_exports.sum_aggregation.value();
        final_exports.rank_output.value() =                           //
            sum_aggregation == 0.0F                                   //
            ? 0.0F                                                    //
            : (final_exports.rank_output.value() /= sum_aggregation); //
      }
    }
  }

  // reverse effects of preconditioning
  preconditioner(output_preconditioned, output, true, bias_handling, debias_anchor);

  // Modify some optional outputs to better reflect utilisation of preconditioning. The
  //   group-mean components regressed out by demeaning are added back to the reported ranks here,
  //   on the final maps only (the per-iteration rank_input fed to the kernel sizing is kept
  //   mean-free). demean_rank() gives the group count whether the demeaning was applied by the
  //   preconditioner (no partitioning) or per partition within Estimate/Recon (partitioning), so
  //   the demean-induced rank contribution is identical in both regimes.
  const ssize_t preconditioner_null_rank = preconditioner.demean_rank();
  if (preconditioner_null_rank > 0) {
    if (final_exports.rank_input.valid()) {
      for (auto l = Loop(final_exports.rank_input)(final_exports.rank_input); l; ++l) {
        if (final_exports.rank_input.value() > 0)
          final_exports.rank_input.value() =                                                                      //
              std::min<uint16_t>(uint16_t(final_exports.rank_input.value()) + uint16_t(preconditioner_null_rank), //
                                 uint16_t(max_rank));                                                             //
      }
    }
    if (final_exports.rank_output.valid()) {
      for (auto l = Loop(final_exports.rank_output)(final_exports.rank_output); l; ++l)
        final_exports.rank_output.value() =                                                             //
            std::min<float>(float(final_exports.rank_output.value()) + float(preconditioner_null_rank), //
                            float(max_rank));                                                           //
    }
  }
  if (vst_image.valid()) {
    if (final_exports.noise_out.valid()) {
      Interp::Cubic<Image<float>> vst_interp(vst_image);
      const Transform transform(subsample->header());
      for (auto l = Loop(final_exports.noise_out)(final_exports.noise_out); l; ++l) {
        vst_interp.scanner(transform.voxel2scanner * Eigen::Vector3d({double(final_exports.noise_out.index(0)),
                                                                      double(final_exports.noise_out.index(1)),
                                                                      double(final_exports.noise_out.index(2))}));
        final_exports.noise_out.value() *= vst_interp.value();
      }
    }
    if (final_exports.lamplus.valid()) {
      Interp::Cubic<Image<float>> vst_interp(vst_image);
      const Transform transform(subsample->header());
      for (auto l = Loop(final_exports.lamplus)(final_exports.lamplus); l; ++l) {
        vst_interp.scanner(transform.voxel2scanner * Eigen::Vector3d({double(final_exports.noise_out.index(0)),
                                                                      double(final_exports.noise_out.index(1)),
                                                                      double(final_exports.noise_out.index(2))}));
        final_exports.lamplus.value() *= vst_interp.value();
      }
    }
  }

  opt = get_options("residual_statistics");
  if (!opt.empty()) {
    Header H_resstats_complex(dwi);
    if (dwi.datatype().is_integer()) {
      H_resstats_complex.datatype() = DataType::Float32;
      H_resstats_complex.datatype().set_byte_order_native();
    }
    H_resstats_complex.ndim() = 3;
    Header H_resstats_real(H_resstats_complex);
    H_resstats_real.datatype() = DataType::Float32;
    H_resstats_real.datatype().set_byte_order_native();
    Image<T> residuals_mean = Image<T>::create(opt[0][0], H_resstats_complex);
    Image<T> residuals_m2 = Image<T>::scratch(H_resstats_complex);
    Image<float> residuals_std = Image<float>::create(opt[0][1], H_resstats_real);
    Image<float> residuals_maxabs = Image<float>::create(opt[0][2], H_resstats_real);
    size_t count = 0;
    for (auto l = Loop("Computing statistics of denoising residuals", dwi)(input, output); l; ++l) {
      assign_pos_of(input, 0, 3).to(residuals_mean, residuals_m2, residuals_maxabs);
      const T diff = T(output.value()) - T(input.value());
      count++;
      const T delta = diff - T(residuals_mean.value());
      residuals_mean.value() += T(delta / default_type(count));
      const T delta2 = diff - T(residuals_mean.value());
      residuals_m2.value() += delta * delta2;
      residuals_maxabs.value() = std::max(default_type(residuals_maxabs.value()), default_type(std::abs(diff)));
    }
    for (auto l = Loop(H_resstats_real)(residuals_m2, residuals_std); l; ++l)
      residuals_std.value() = std::sqrt(std::abs(T(residuals_m2.value())) / count);
  }
}

void run() {
  auto dwi = Header::open(argument[0]);
  if (dwi.ndim() < 4)
    throw Exception("input image must be at least 4-dimensional");
  if (Denoise::num_volumes(dwi) == 1)
    throw Exception("input image must be non-singleton across non-spatial dimensions");

  const Demodulation demodulation = select_demodulation(dwi);
  const demean_type demean = select_demean(dwi);
  const decomp_type decomposition = get_option_choice("decomposition", default_decomposition);

  // Resolve the requested variance-stabilising transform up-front:
  //   -vst_method none disables the transform entirely, which makes iterative
  //   refinement of the noise level pointless (handled below) and is incompatible
  //   with -noise_in (which exists only to parameterise the transform).
  const NoiseModel::vst_method_t vst_method =
      get_option_choice("vst_method", NoiseModel::vst_method_t::FOI);
  const bool vst_none = (vst_method == NoiseModel::vst_method_t::NONE);

  // A pre-estimated noise level provided via -noise_in is authoritative:
  //   it parameterises the variance-stabilising transform (the VST scale),
  //   and via the Fixed/Import estimator (make_estimator below) it bypasses
  //   noise level estimation, yielding sigma^2 ~ 1 on the stabilised data
  //   (equivalent to -estimator unity); see vst_plan.md section 6.2.
  Image<float> user_vst_image;
  auto opt = get_options("noise_in");
  if (!opt.empty()) {
    if (vst_none)
      throw Exception("Options -noise_in and -vst_method none are incompatible: "
                      "a pre-estimated noise level is used to parameterise the variance-stabilising transform, "
                      "which is disabled by -vst_method none");
    if (demean == demean_type::NONE) {
      WARN("Application of variance-stabilising transform in the absence of demeaning may be erroneous");
    }
    user_vst_image = Denoise::import_vst_noise_map(opt[0][0], dwi);
  }

  const aggregator_type aggregator = get_option_choice("aggregator", aggregator_type::GAUSSIAN);

  const bias_handling_t bias_handling =
      get_options("preserve_noise_bias").empty() ? bias_handling_t::DEBIAS : bias_handling_t::PRESERVE;
  // -preserve_noise_bias governs how the noise-floor bias of the magnitude noise
  //   distribution is handled when reversing the variance-stabilising transform. It is
  //   meaningless whenever the noise model is linear (Gaussian / identity), i.e. when there
  //   is no estimated noise bias to either preserve or remove. This linear case arises from
  //   complex input data (Gaussian noise) or from the user requesting a linear transform
  //   (-vst_method none / linear) on the command line; mirrors make_noise_model().
  if (bias_handling == bias_handling_t::PRESERVE) {
    const bool complex = dwi.datatype().is_complex();
    const bool vst_linear = (vst_method == NoiseModel::vst_method_t::LINEAR);
    if (complex || vst_none || vst_linear) {
      const std::string reason =
          vst_none    ? "-vst_method none applies no variance-stabilising transform"               //
          : complex   ? "the input data are complex, for which the noise is Gaussian-distributed"   //
                      : "-vst_method linear uses a linear (Gaussian) noise model";                  //
      WARN("Option -preserve_noise_bias has no effect: " + reason + ", "
           "so the noise model is linear and there is no estimated noise bias "
           "to either preserve or remove");
    }
  }

  // Operating point for reversing the non-linear variance-stabilising transform when debiasing
  //   (see debias_anchor_t); the default inverts the transform at each volume's own denoised
  //   value, so debiasing no longer depends on the demeaning grouping.
  const debias_anchor_t debias_anchor = get_option_choice("debias_anchor", debias_anchor_t::SAMPLE);

  // Resolve the iteration schedule. When the user supplies -schedule it is the single
  //   source of truth for both the spatial and temporal sub-sampling of each iteration;
  //   otherwise the command's bundled default schedule is loaded from file (Schedule::load_default).
  //   "one-pass" operation is simply a single-row schedule. -fixed_rank imposes the signal
  //   rank at a single kernel size, and -vst_method none removes the coupling between
  //   iterations; either reduces to a single-iteration schedule.
  std::vector<Iterative::Iteration> iterations;
  const bool fixed_rank = !get_options("fixed_rank").empty();
  if (Schedule::requested()) {
    iterations = Schedule::load("dwidenoise2");
    // Without a variance-stabilising transform there is no coupling between iterations, so the
    //   per-iteration refinement of a multi-row schedule cannot propagate and is wasted
    //   computation; a single-row schedule (e.g. the bundled "legacy" schedule) is, however,
    //   perfectly meaningful under -vst_method none.
    if (vst_none && iterations.size() > 1)
      throw Exception("Option -vst_method none cannot be combined with a -schedule of more than "
                      "one row: without a variance-stabilising transform there is no coupling "
                      "between iterations for the additional schedule rows to control; "
                      "use a single-row schedule");
  } else if (vst_none || fixed_rank) {
    if (vst_none)
      WARN("-vst_method none: no variance-stabilising transform is applied, so iteratively "
           "refining the noise level estimate would have no effect on subsequent iterations "
           "and is therefore wasted computation; performing a single pass instead");
    const ssize_t f = (aggregator == aggregator_type::EXCLUSIVE) ? ssize_t(1) : default_spatial_subsample_ratio;
    Iterative::Iteration config;
    config.spatial_subsample_ratios = {f, f, f};
    config.kernel_size_multiplier = 1.0;
    config.smooth_noiseout = noise_smooth_type::NONE;
    config.temporal_subsample = 1.0;
    config.update_noise = true; // a single-pass schedule must estimate the noise level
    iterations.push_back(config);
  } else {
    iterations = Schedule::load_default("dwidenoise2");
    Schedule::warn_if_default_schedule_slow(Denoise::num_volumes(dwi));
  }
  std::shared_ptr<SpatialSubsample> final_subsample =
      std::make_shared<SpatialSubsample>(dwi, iterations.back().spatial_subsample_ratios);

  // Resolve per-iteration update_noise defaults: non-final unset -> true; final unset ->
  //   false (carry the prior estimate through the reconstruction via the dummy Unity estimator).
  for (size_t i = 0; i + 1 < iterations.size(); ++i)
    if (!iterations[i].update_noise.has_value())
      iterations[i].update_noise = true;
  if (!iterations.back().update_noise.has_value())
    iterations.back().update_noise = false;

  // smooth_noise smooths an iteration's freshly estimated noise map before it is passed on; that
  //   is only meaningful when the iteration (re)estimates the noise level. With update_noise now
  //   resolved, reject any iteration that requests smoothing without estimating (the final
  //   reconstruction row, whose update_noise defaults to false, is the only one that can reach
  //   here, as non-final rows are already required to have update_noise true).
  for (const auto &it : iterations)
    if (it.smooth_noiseout == noise_smooth_type::SMOOTH && !it.update_noise.value())
      throw Exception("A schedule iteration sets smooth_noise true but does not (re)estimate the "
                      "noise level in that iteration (update_noise false), so there is no freshly "
                      "estimated noise map to smooth; smooth_noise may be true only when "
                      "update_noise is true in the same iteration");

  // dwidenoise2's final (reconstruction) pass must reconstruct every volume.
  if (iterations.back().temporal_subsample < 1.0)
    throw Exception("dwidenoise2 requires the final (reconstruction) schedule row to use all "
                    "volumes (temporal_subsample = 1); sub-sample only the noise-estimation iterations");
  // -fixed_rank is only meaningful at a single kernel size, as the signal rank varies with it.
  if (fixed_rank) {
    for (const auto &it : iterations)
      if (it.kernel_size_multiplier != 1.0)
        throw Exception("Option -fixed_rank cannot be combined with a schedule that uses non-unity "
                        "kernel_multiplier values, as the signal rank varies with kernel size; "
                        "use a schedule whose kernel_multiplier is 1 throughout");
  }
  // Some source must establish the noise level: at least one estimating iteration, or a -noise_in seed.
  {
    bool any_update = false;
    for (const auto &it : iterations)
      any_update = any_update || it.update_noise.value();
    if (!any_update && get_options("noise_in").empty())
      throw Exception("The schedule never estimates the noise level (every update_noise is false) "
                      "and no -noise_in seed was provided; there is no noise level with which to denoise");
  }
  // For a multi-stage schedule, -noise_in only seeds the first iteration; the noise map used to
  //   denoise is re-estimated internally and differs from the supplied image.
  if (!get_options("noise_in").empty() && iterations.size() > 1)
    WARN("Option -noise_in provides only an initial noise level seed for the iterative schedule; "
         "the noise map used to denoise the data is re-estimated internally and differs from the "
         "supplied image");

  // -rankpermm_in seeds the reconstruction kernel's signal-rank density. A multi-resolution schedule
  //   derives that density itself from its noise-estimation iterations, so a supplied map would only
  //   affect the first iteration's kernel and then be discarded; reject the combination outright. The
  //   option is meaningful with a single-row (e.g. "apriori") schedule, which has no such iteration.
  if (!get_options("rankpermm_in").empty() && iterations.size() > 1)
    throw Exception("Option -rankpermm_in provides a precomputed signal-rank density to size the "
                    "reconstruction kernel and is only meaningful with a single-row schedule (e.g. "
                    "the bundled \"apriori\" schedule); a multi-row schedule derives that density "
                    "internally from its noise-estimation iterations");

  // The exclusive aggregator assigns each voxel only the result of its own patch; if the final
  //   (reconstruction) iteration sub-samples space, the majority of voxels are never the centre
  //   of a patch and would be left empty in the output. Reject this combination outright rather
  //   than producing a mostly-empty denoised series.
  if (aggregator == aggregator_type::EXCLUSIVE &&
      *std::max_element(final_subsample->get_factors().begin(), final_subsample->get_factors().end()) > 1)
    throw Exception("Option -aggregator exclusive cannot be combined with a schedule whose final "
                    "(reconstruction) iteration performs non-unity spatial sub-sampling, as the "
                    "majority of output voxels would be left empty (only voxels at the centre of a "
                    "patch are reconstructed); use unity spatial sub-sampling on the final iteration "
                    "(e.g. the bundled \"legacy\" schedule)");

  auto estimator = Estimator::make_estimator(user_vst_image, true);

  const filter_type filter = get_option_choice(
      "filter", get_options("fixed_rank").empty() ? filter_type::OPTSHRINK : filter_type::TRUNCATE);

  Exports final_exports(dwi, final_subsample->header());
  opt = get_options("noise_out");
  if (!opt.empty())
    final_exports.set_noise_out(opt[0][0].as_text());
  opt = get_options("lamplus");
  if (!opt.empty())
    final_exports.set_lamplus(opt[0][0].as_text());
  opt = get_options("rank_pcanonzero");
  if (!opt.empty())
    final_exports.set_rank_pcanonzero(opt[0][0].as_text());
  opt = get_options("rank_input");
  if (!opt.empty())
    final_exports.set_rank_input(opt[0][0].as_text());
  opt = get_options("rank_output");
  if (!opt.empty()) {
    if (aggregator == aggregator_type::EXCLUSIVE && filter == filter_type::TRUNCATE) {
      WARN("When using -aggregator exclusive and -filter truncate, "
           "the output of -rank_output will be identical to the output of -rank_input, "
           "as there is no aggregation of multiple patches per output voxel "
           "and no optimal shrinkage to reduce output rank relative to estimated input rank");
    }
    final_exports.set_rank_output(opt[0][0].as_text());
  }
  opt = get_options("sum_optshrink");
  if (!opt.empty()) {
    if (filter == filter_type::TRUNCATE) {
      WARN("Note that with a truncation filter, "
           "output image from -sumweights option will be equivalent to rank_input");
    }
    final_exports.set_sum_optshrink(opt[0][0].as_text());
  }
  opt = get_options("max_dist");
  if (!opt.empty())
    final_exports.set_max_dist(opt[0][0].as_text());
  opt = get_options("voxelcount");
  if (!opt.empty())
    final_exports.set_voxelcount(opt[0][0].as_text());
  opt = get_options("patchcount");
  if (!opt.empty())
    final_exports.set_patchcount(opt[0][0].as_text());
  opt = get_options("sum_aggregation");
  if (!opt.empty()) {
    if (aggregator == aggregator_type::EXCLUSIVE) {
      WARN("Output from -sum_aggregation will just contain 1 for every voxel processed: "
           "no patch aggregation takes place when output series comes exclusively from central patch");
    }
    final_exports.set_sum_aggregation(opt[0][0].as_text());
  } else if (aggregator != aggregator_type::EXCLUSIVE) {
    final_exports.set_sum_aggregation();
  }
  opt = get_options("variance_removed");
  if (!opt.empty())
    final_exports.set_variance_removed(opt[0][0].as_text());
  opt = get_options("eigenspectra");
  if (!opt.empty())
    final_exports.set_eigenspectra_path(opt[0][0].as_text());

  int prec = (get_option_choice("datatype", dtype_t::FLOAT32) == dtype_t::FLOAT64) ? 1 : 0;
  if (dwi.datatype().is_complex())
    prec += 2; // support complex input data
  switch (prec) {
  case 0:
    assert(demodulation.axes.empty());
    INFO("select real float32 for processing");
    run<float>(         //
        dwi,            //
        demodulation,   //
        demean,         //
        user_vst_image, //
        iterations,     //
        decomposition,  //
        estimator,      //
        filter,         //
        aggregator,     //
        bias_handling,  //
        debias_anchor,  //
        argument[1].as_text(), //
        final_exports); //
    break;
  case 1:
    assert(demodulation.axes.empty());
    INFO("select real float64 for processing");
    run<double>(        //
        dwi,            //
        demodulation,   //
        demean,         //
        user_vst_image, //
        iterations,     //
        decomposition,  //
        estimator,      //
        filter,         //
        aggregator,     //
        bias_handling,  //
        debias_anchor,  //
        argument[1].as_text(), //
        final_exports); //
    break;
  case 2:
    INFO("select complex float32 for processing");
    run<cfloat>(        //
        dwi,            //
        demodulation,   //
        demean,         //
        user_vst_image, //
        iterations,     //
        decomposition,  //
        estimator,      //
        filter,         //
        aggregator,     //
        bias_handling,  //
        debias_anchor,  //
        argument[1].as_text(), //
        final_exports); //
    break;
  case 3:
    INFO("select complex float64 for processing");
    run<cdouble>(       //
        dwi,            //
        demodulation,   //
        demean,         //
        user_vst_image, //
        iterations,     //
        decomposition,  //
        estimator,      //
        filter,         //
        aggregator,     //
        bias_handling,  //
        debias_anchor,  //
        argument[1].as_text(), //
        final_exports); //
    break;
  }
}
